-- Master Data tables for Custom PPT Presentation Themes & Uploaded Front Page Cover Templates

CREATE TABLE IF NOT EXISTS ppt_master_themes (
  id VARCHAR(36) PRIMARY KEY,
  name VARCHAR(255) NOT NULL,
  tagline VARCHAR(255) NOT NULL DEFAULT '',
  badge VARCHAR(100) NOT NULL DEFAULT 'CUSTOM THEME',
  primary_color VARCHAR(50) NOT NULL DEFAULT '0F172A',
  accent_color VARCHAR(50) NOT NULL DEFAULT 'F59E0B',
  card_bg VARCHAR(50) NOT NULL DEFAULT '1E293B',
  text_color VARCHAR(50) NOT NULL DEFAULT 'FFFFFF',
  is_dark TINYINT(1) NOT NULL DEFAULT 1,
  bg_image_url TEXT NULL,
  theme_config_json LONGTEXT NULL,
  is_active TINYINT(1) NOT NULL DEFAULT 1,
  created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS ppt_front_pages (
  id VARCHAR(36) PRIMARY KEY,
  title VARCHAR(255) NOT NULL,
  description VARCHAR(500) NULL,
  image_url TEXT NOT NULL,
  thumbnail_url TEXT NULL,
  overlay_text TINYINT(1) NOT NULL DEFAULT 1,
  text_theme VARCHAR(50) NOT NULL DEFAULT 'light',
  is_active TINYINT(1) NOT NULL DEFAULT 1,
  created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
